#!/usr/bin/env node
// Builds the Daebot single-file binary with `bun build --compile`, with the web UI and the package version baked in.
//   node scripts/build-bin.mjs                         host target -> dist/bin/daebot-<os>-<arch>
//   node scripts/build-bin.mjs --target bun-darwin-x64 one target (bun-darwin-arm64|x64, bun-linux-x64|arm64, bun-windows-x64|arm64)
//   node scripts/build-bin.mjs --all                   every target above
//   --outdir DIR  change the output directory (default dist/bin)
// While bun runs, src/embedded.generated.ts holds the real assets; it is restored to the empty stub afterwards (even on failure),
// so the Node path and git status stay clean. No dependencies.
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const GENERATED = join(root, "src", "embedded.generated.ts");
const STUB = `// STUB. scripts/build-bin.mjs overwrites this file while it runs \`bun build --compile\` (web/ files as base64 plus the
// package version) and restores this stub afterwards, so the Node path never embeds anything.
export const EMBEDDED_VERSION: string = "";
export const EMBEDDED_FILES: Record<string, string> = {};
`;
const TARGETS = ["bun-darwin-arm64", "bun-darwin-x64", "bun-linux-x64", "bun-linux-arm64", "bun-windows-x64", "bun-windows-arm64"];
const SKIP_DIRS = new Set(["login-src", "screenshots", "node_modules"]);

/** Every servable file under web/ as { "brand/mbot.js": base64 }. Dotfiles and build-only folders are left out. */
export function collectSite(webDir) {
  const out = {};
  const walk = (dir) => {
    for (const name of readdirSync(dir).sort()) {
      if (name.startsWith(".")) continue;
      const p = join(dir, name);
      const st = statSync(p);
      if (st.isDirectory()) { if (!SKIP_DIRS.has(name)) walk(p); continue; }
      if (st.isFile()) out[relative(webDir, p).split(sep).join("/")] = readFileSync(p).toString("base64");
    }
  };
  walk(webDir);
  return out;
}

export function renderModule(version, files) {
  return `// GENERATED by scripts/build-bin.mjs for one compile. Do not commit.
export const EMBEDDED_VERSION: string = ${JSON.stringify(version)};
export const EMBEDDED_FILES: Record<string, string> = ${JSON.stringify(files)};
`;
}

export function outName(target) {
  const [, os, arch] = target.split("-");
  return `daebot-${os === "windows" ? "windows" : os}-${arch}${os === "windows" ? ".exe" : ""}`;
}

function hostTarget() {
  const os = process.platform === "win32" ? "windows" : process.platform;
  return `bun-${os}-${process.arch}`;
}

function main(argv) {
  const get = (f) => { const i = argv.indexOf(f); return i >= 0 ? argv[i + 1] : undefined; };
  const targets = argv.includes("--all") ? TARGETS : [get("--target") ?? hostTarget()];
  for (const t of targets) if (!TARGETS.includes(t)) { console.error(`unknown target ${t}; use one of ${TARGETS.join(", ")}`); return 1; }
  const outdir = get("--outdir") ?? join(root, "dist", "bin");
  mkdirSync(outdir, { recursive: true });
  const version = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version;
  const files = collectSite(join(root, "web"));
  console.log(`embedding ${Object.keys(files).length} web files, version ${version}`);
  writeFileSync(GENERATED, renderModule(version, files));
  let code = 0;
  try {
    for (const t of targets) {
      const outfile = join(outdir, outName(t));
      const r = spawnSync("bun", ["build", "--compile", `--target=${t}`, join(root, "src", "cli.ts"), "--outfile", outfile], { cwd: root, stdio: "inherit" });
      if (r.status !== 0) { console.error(`bun build failed for ${t}`); code = 1; break; }
      console.log(`built ${outfile} (${(statSync(outfile).size / 1048576).toFixed(1)} MB)`);
    }
  } finally {
    writeFileSync(GENERATED, STUB);
  }
  return code;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exit(main(process.argv.slice(2)));
